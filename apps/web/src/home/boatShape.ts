const fmt = (n: number) => +n.toFixed(2);

/** 闭合多边形 → SVG path */
export function polygonPath(points: Pt[]): string {
  return `M${points.map(([x, y]) => `${fmt(x)} ${fmt(y)}`).join("L")}Z`;
}

/** 两条等长折线围成的闭合带 → SVG path（外沿正走、内沿倒走） */
export function bandPath(outer: Pt[], inner: Pt[]): string {
  const forward = outer.map(([x, y]) => `${fmt(x)} ${fmt(y)}`).join("L");
  const backward = [...inner]
    .reverse()
    .map(([x, y]) => `${fmt(x)} ${fmt(y)}`)
    .join("L");
  return `M${forward}L${backward}Z`;
}
